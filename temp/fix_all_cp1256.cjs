// Reverse: Unicode → CP1256 byte
const toCP1256 = new Map();
for (const [byte, uni] of cp1256) toCP1256.set(uni, byte);

function decodeUTF8(bytes) {
  let out = "";
  for (let i = 0; i < bytes.length; ) {
    const b = bytes[i];
    let cp, len;
    if (b < 0x80) { cp = b; len = 1; }
    else if ((b & 0xE0) === 0xC0) { cp = b & 0x1F; len = 2; }
    else if ((b & 0xF0) === 0xE0) { cp = b & 0x0F; len = 3; }
    else if ((b & 0xF8) === 0xF0) { cp = b & 0x07; len = 4; }
    else return null;
    if (i + len > bytes.length) return null;
    for (let j = 1; j < len; j++) {
      if ((bytes[i+j] & 0xC0) !== 0x80) return null;
      cp = (cp << 6) | (bytes[i+j] & 0x3F);
    }
    if (cp > 0x10FFFF) return null;
    out += String.fromCodePoint(cp);
    i += len;
  }
  return out;
}

function tryReverse(chars) {
  const bytes = [];
  for (const c of chars) {
    const b = toCP1256.get(c);
    if (b === undefined) return null;
    bytes.push(b);
  }
  return decodeUTF8(bytes);
}

const files = [];
function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const f = path.join(dir, e.name);
    if (e.isDirectory() && e.name !== "node_modules") walk(f);
    else if (/\.(tsx?|js|cjs|mjs)$/i.test(e.name)) files.push(f);
  }
}
walk(srcDir);

let total = 0, fileCount = 0;
for (const f of files) {
  const orig = fs.readFileSync(f, "utf8");
  const arr = [...orig];
  let changed = false, i = 0;
  
  while (i < arr.length) {
    const cp = arr[i].charCodeAt(0);
    
    // Try 3-char sequence
    if (i + 2 < arr.length) {
      const seq = [arr[i], arr[i+1], arr[i+2]].map(c => c.charCodeAt(0));
      const dec = tryReverse(seq);
      if (dec && dec.length === 1 && dec.charCodeAt(0) >= 0x2000) {
        arr[i] = dec[0];
        arr.splice(i+1, 2);
        changed = true; total++;
        continue;
      }
    }
    
    // Try 2-char sequence
    if (i + 1 < arr.length) {
      const seq = [arr[i], arr[i+1]].map(c => c.charCodeAt(0));
      const dec = tryReverse(seq);
      if (dec && dec.length === 1 && dec.charCodeAt(0) >= 0x80) {
        arr[i] = dec[0];
        arr.splice(i+1, 1);
        changed = true; total++;
        continue;
      }
    }
    
    i++;
  }
  
  if (changed) {
    fs.writeFileSync(f, arr.join(""), "utf8");
    const rel = path.relative(srcDir, f);
    console.log("Fixed: " + rel);
    fileCount++;
  }
}

console.log(`\nDone: ${fileCount} files changed, ${total} replacements.`);
