document.addEventListener('DOMContentLoaded', function() {
  renderUniversitiesList();
  renderActiveUniversityBanner();
  renderSubjects(1);

  // Region Filter Click Handlers
  document.querySelectorAll('.region-btn').forEach(btn => {
    btn.addEventListener('click', function() {
      document.querySelectorAll('.region-btn').forEach(b => b.classList.remove('active'));
      this.classList.add('active');
      currentRegion = this.getAttribute('data-region');
      
      const filtered = currentRegion === 'all' 
        ? EGYPT_UNIVERSITIES 
        : EGYPT_UNIVERSITIES.filter(u => u.region === currentRegion);
      if (filtered.length > 0) {
        currentUniId = filtered[0].id;
      }

      renderUniversitiesList();
      renderActiveUniversityBanner();
      renderSubjects(currentYear);
    });
  });

  // Year Switcher Tabs
  document.querySelectorAll('.year-btn').forEach(btn => {
    btn.addEventListener('click', function() {
      document.querySelectorAll('.year-btn').forEach(b => b.classList.remove('active'));
      this.classList.add('active');
      currentYear = parseInt(this.getAttribute('data-year'));
      renderSubjects(currentYear);
    });
  });
});

