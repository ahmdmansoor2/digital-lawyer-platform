function calcCumulativeGPA() {
  const g1 = parseFloat(document.getElementById('gpa1').value) || 0;
  const g2 = parseFloat(document.getElementById('gpa2').value) || 0;
  const g3 = parseFloat(document.getElementById('gpa3').value) || 0;
  const g4 = parseFloat(document.getElementById('gpa4').value) || 0;

  if (!g1 || !g2 || !g3 || !g4) {
    alert('يرجى إدخال درجات أو نسب الفرق الأربعة لحساب التقدير التراكمي بدقة.');
    return;
  }

  const p1 = g1 <= 100 ? g1 : (g1 / 200) * 100;
  const p2 = g2 <= 100 ? g2 : (g2 / 200) * 100;
  const p3 = g3 <= 100 ? g3 : (g3 / 200) * 100;
  const p4 = g4 <= 100 ? g4 : (g4 / 200) * 100;

  const totalPercentage = ((p1 + p2 + p3 + p4) / 4).toFixed(2);

  let grade = '';
  let color = '';
  let judicialEligibility = '';

  if (totalPercentage >= 85) {
    grade = 'ممتاز مع مرتبة الشرف 🏆';
    color = '#34d399';
    judicialEligibility = '🟢 فرصة تنافسية عليا للتعيين بالنيابة العامة، مجلس الدولة، وهيئة قضايا الدولة، والتعيين معيداً بالجامعة.';
  } else if (totalPercentage >= 75) {
    grade = 'جيد جداً 🌟';
    color = '#818cf8';
    judicialEligibility = '🟢 مؤهل رسمياً للتقديم في كافة الهيئات القضائية (النيابة العامة، مجلس الدولة، النيابة الإدارية، قضايا الدولة) والتسجيل بالدراسات العليا.';
  } else if (totalPercentage >= 65) {
    grade = 'جيد 📘';
    color = '#fbbf24';
    judicialEligibility = '🟡 مؤهل للتقديم في بعض الهيئات القضائية وفق شروط كل إعلان، ومؤهل فوراً للقيد بالجدول العام بنقابة المحامين.';
  } else {
    grade = 'مقبول 📜';
    color = '#f87171';
    judicialEligibility = '🔴 مؤهل للقيد بنقابة المحامين وممارسة العمل الحر بالشركات والمؤسسات القانونية.';
  }

  const resBox = document.getElementById('gpaResult');
  resBox.style.display = 'block';
  resBox.innerHTML = 
    '<div style="font-size: 15px; color: #fff; margin-bottom: 6px;">النسبة التراكمية العامة: <strong style="font-size: 22px; color: ' + color + ';">' + totalPercentage + '%</strong></div>' +
    '<div style="font-size: 17px; font-weight: 800; color: ' + color + '; margin-bottom: 10px;">التقدير العام: ' + grade + '</div>' +
    '<div style="font-size: 13px; color: #cbd5e1; background: rgba(0,0,0,0.3); padding: 10px; border-radius: 8px; text-align: right;">' +
      judicialEligibility +
    '</div>';
}

