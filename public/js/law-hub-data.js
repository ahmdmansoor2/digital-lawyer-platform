function openQuiz(id) {
  const s = getSubjectById(id);
  if (!s || !s.quiz || s.quiz.length === 0) return;
  
  let html = 
    '<h2 style="color: #34d399; font-size: 20px; margin-top:0; margin-bottom: 6px;">📝 امتحان بابل شيت تجريبي: ' + s.title + '</h2>' +
    '<p style="color: #94a3b8; font-size: 13px; margin-bottom: 20px;">اختر الإجابة الصحيحة واضغط عليها لمعرفة النتيجة والتأصيل القانوني الفوري وفق أحكام محكمة النقض ونصوص التشريع.</p>';

  s.quiz.forEach((q, idx) => {
    html += 
      '<div class="quiz-question" id="q_' + idx + '">' +
        '<div class="quiz-q-title">س ' + (idx + 1) + ': ' + q.q + '</div>' +
        '<div class="quiz-options">' +
          q.options.map((opt, optIdx) => 
            '<button class="quiz-option" onclick="checkAnswer(' + idx + ', ' + optIdx + ', ' + q.correct + ')">' +
              String.fromCharCode(65 + optIdx) + ') ' + opt +
            '</button>'
          ).join('') +
        '</div>' +
        '<div class="quiz-rationale" id="rat_' + idx + '">' +
          '💡 <strong>التأصيل القانوني والسند:</strong> ' + q.rationale +
        '</div>' +
      '</div>';
  });

  document.getElementById('modalBody').innerHTML = html;
  document.getElementById('contentModal').classList.add('open');
}

function checkAnswer(qIdx, selectedIdx, correctIdx) {
  const qBox = document.getElementById('q_' + qIdx);
  const options = qBox.querySelectorAll('.quiz-option');
  const rationale = document.getElementById('rat_' + qIdx);

  options.forEach((btn, idx) => {
    btn.disabled = true;
    if (idx === correctIdx) {
      btn.classList.add('correct');
    } else if (idx === selectedIdx && selectedIdx !== correctIdx) {
      btn.classList.add('wrong');
    }
  });

  if (rationale) rationale.style.display = 'block';
}

