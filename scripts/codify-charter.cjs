let agentsContent = fs.readFileSync(agentsPath, 'utf8');

const marker = '## 🛑 القواعد الدستورية الاثنتا عشرة الصارمة';
const idx = agentsContent.indexOf(marker);
if (idx !== -1) {
  const headerPart = agentsContent.slice(0, idx);
  const restPart = agentsContent.slice(idx);
  agentsContent = headerPart + charter + '\n\n---\n\n' + restPart;
  fs.writeFileSync(agentsPath, agentsContent, 'utf8');
  console.log('✅ Successfully codified Charter into AGENTS.md');
} else {
  console.error('❌ Marker not found in AGENTS.md');
}

