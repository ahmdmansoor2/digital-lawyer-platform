function createBodyP(runs, opts = {}) {
  let textRuns = [];
  if (typeof runs === 'string') {
    textRuns = [
      new TextRun({
        text: toArabicDigits(runs),
        font: FONT_NAME,
        size: opts.size || 32, // 16pt
        bold: opts.bold || false,
        italics: opts.italics || false,
      }),
    ];
  } else if (Array.isArray(runs)) {
    textRuns = runs.map(r => {
      if (typeof r === 'string') {
        return new TextRun({
          text: toArabicDigits(r),
          font: FONT_NAME,
          size: opts.size || 32, // 16pt
          bold: opts.bold || false,
        });
      }
      return new TextRun({
        text: toArabicDigits(r.text),
        font: FONT_NAME,
        size: r.size || opts.size || 32,
        bold: r.bold || false,
        italics: r.italics || false,
        underline: r.underline ? {} : undefined,
      });
    });
  }

  return new Paragraph({
    alignment: opts.alignment || AlignmentType.JUSTIFIED,
    bidirectional: true,
    spacing: {
      before: opts.spacingBefore !== undefined ? opts.spacingBefore : 80,
      after: opts.spacingAfter !== undefined ? opts.spacingAfter : 80,
      line: 300, // 1.25 line spacing
    },
    indent: opts.indent ? { right: opts.indent } : undefined,
    children: textRuns,
  });
}

function createQuoteBox(title, bodyRuns) {
  const cellChildren = [];
  if (title) {
    cellChildren.push(
      new Paragraph({
        alignment: AlignmentType.RIGHT,
        bidirectional: true,
        spacing: { before: 60, after: 60, line: 260 },
        children: [
          new TextRun({
            text: toArabicDigits(title),
            font: FONT_NAME,
            size: 30, // 15pt
            bold: true,
          }),
        ],
      })
    );
  }

  const pList = Array.isArray(bodyRuns) ? bodyRuns : [bodyRuns];
  pList.forEach(p => {
    if (typeof p === 'string') {
      cellChildren.push(
        new Paragraph({
          alignment: AlignmentType.JUSTIFIED,
          bidirectional: true,
          spacing: { before: 40, after: 40, line: 280 },
          children: [
            new TextRun({
              text: toArabicDigits(p),
              font: FONT_NAME,
              size: 28, // 14pt
              italics: true,
            }),
          ],
        })
      );
    } else {
      cellChildren.push(p);
    }
  });

  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    alignment: AlignmentType.CENTER,
    rows: [
      new TableRow({
        children: [
          new TableCell({
            width: { size: 100, type: WidthType.PERCENTAGE },
            margins: { top: 120, bottom: 120, left: 180, right: 180 },
            borders: {
              top: { style: BorderStyle.SINGLE, size: 8, color: 'B8860B' },
              bottom: { style: BorderStyle.SINGLE, size: 8, color: 'B8860B' },
              right: { style: BorderStyle.SINGLE, size: 24, color: '003366' },
              left: { style: BorderStyle.NONE },
            },
            shading: { fill: 'F9FBFD' },
            children: cellChildren,
          }),
        ],
      }),
    ],
  });
}

