const hindiDigits = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
function toHindiDigits(str) {
  if (typeof str !== 'string') return str;
  return str.replace(/[0-9]/g, w => hindiDigits[+w]);
}

function createCell(text, widthPct, isHeader = false, align = AlignmentType.CENTER, bold = false) {
  const convertedText = toHindiDigits(text);
  return new TableCell({
    width: { size: widthPct, type: WidthType.PERCENTAGE },
    verticalAlign: VerticalAlign.CENTER,
    shading: isHeader
      ? { fill: "D9D9D9", type: ShadingType.CLEAR }
      : { fill: "FFFFFF", type: ShadingType.CLEAR },
    margins: { top: 120, bottom: 120, left: 140, right: 140 },
    borders: {
      top: { style: BorderStyle.SINGLE, size: 4, color: "000000" },
      bottom: { style: BorderStyle.SINGLE, size: 4, color: "000000" },
      left: { style: BorderStyle.SINGLE, size: 4, color: "000000" },
      right: { style: BorderStyle.SINGLE, size: 4, color: "000000" }
    },
    children: [
      new Paragraph({
        alignment: align,
        bidirectional: true,
        spacing: { before: 40, after: 40, line: 260 },
        children: [
          new TextRun({
            text: convertedText,
            font: "Times New Roman",
            size: isHeader ? 22 : 20, // 11pt header, 10pt content
            bold: isHeader || bold,
            color: "000000"
          })
        ]
      })
    ]
  });
}

