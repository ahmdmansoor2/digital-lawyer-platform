async function sendTelegram(msg) {
  if (!TG_TOKEN || !TG_CHAT) return;
  try {
    const url = `https://api.telegram.org/bot${TG_TOKEN}/sendMessage`;
    await fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        chat_id: TG_CHAT,
        text: msg,
        parse_mode: 'HTML'
      })
    });
  } catch (err) {
    console.error('Telegram notification error:', err.message);
  }
}

async function publishSeries(forceDay = null) {
  const daysMap = ['sunday', 'monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday'];
  const dayKey = forceDay || daysMap[new Date().getDay()];
  const item = SERIES_TEMPLATES[dayKey];

  if (!item) {
    console.error(`❌ لا يوجد قالب لليوم: ${dayKey}`);
    return;
  }

  console.log(`🚀 جاري نشر سلسلة اليوم: [${item.name}] على صفحة فيسبوك الرسمية...`);

  if (!PAGE_ID || !PAGE_TOKEN) {
    console.error('❌ خطأ: FB_PAGE_ID أو FB_PAGE_TOKEN غير معرف في .env');
    return;
  }

  try {
    const res = await fetch(`https://graph.facebook.com/v20.0/${PAGE_ID}/feed`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        message: item.message,
        link: item.link,
        access_token: PAGE_TOKEN
      })
    });

    const data = await res.json();
    if (data.id) {
      const postUrl = `https://www.facebook.com/${data.id}`;
      console.log('✅ تم النشر بنجاح تام على فيسبوك!');
      console.log(`معرف المنشور: ${data.id}`);
      console.log(`رابط المنشور: ${postUrl}`);

      const logPath = path.join(__dirname, 'facebook-published-log.json');
      let logData = { entries: [] };
      if (fs.existsSync(logPath)) {
        try {
          const parsed = JSON.parse(fs.readFileSync(logPath, 'utf8'));
          if (parsed && Array.isArray(parsed.entries)) logData = parsed;
          else if (Array.isArray(parsed)) logData = { entries: parsed };
        } catch (e) {}
      }
      logData.entries.unshift({
        id: data.id,
        date: new Date().toISOString(),
        day: dayKey,
        title: item.name,
        url: postUrl
      });
      fs.writeFileSync(logPath, JSON.stringify(logData, null, 2), 'utf8');

      await sendTelegram(`📢 <b>تم نشر منشور السلسلة الأسبوعية على فيسبوك!</b>\n\n📌 <b>السلسلة:</b> ${item.name}\n🔗 <b>رابط المنشور:</b> <a href="${postUrl}">فتح على فيسبوك</a>\n\n🌐 تم توجيه المتابعين لدعم المنصة وحاسباتها القانونية.`);
    } else {
      console.error('❌ خطأ من فيسبوك:', data);
    }
  } catch (err) {
    console.error('❌ فشل الاتصال بواجهة Graph API:', err);
  }
}

const targetDay = process.argv[2] || null;
publishSeries(targetDay);
